// Generates src/components/wallet/compat.css: rgb()-alpha versions of every `<utility>-<color>/<alpha>` class used by
// the wallet, for engines without color-mix() (Chromium < 111 — e.g. Huawei system WebViews on Chromium 99), where
// Tailwind v4's @supports fallback is the *opaque* colour. Re-run after adding new translucent colour classes:
//   node scripts/wallet-compat-css.mjs
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOTS = ["src/app/wallet", "src/components/wallet"];
const OUT = "src/components/wallet/compat.css";

// theme colours as "r g b" + base alpha (globals.css: [data-theme="arc"] light / [data-theme="terminal"] dark)
const THEMES = {
  arc: { background: "244 244 244", foreground: "17 17 17", card: "255 255 255", muted: "236 236 236", "muted-foreground": ["17 17 17", 0.55], border: ["17 17 17", 0.1], primary: "17 17 17" },
  terminal: { background: "0 0 0", foreground: "242 242 242", card: "13 13 13", muted: "26 26 26", "muted-foreground": ["242 242 242", 0.55], border: ["255 255 255", 0.1], primary: "242 242 242" },
};
const FIXED = { up: "38 166 154", down: "239 83 80", black: "0 0 0", white: "255 255 255" };

const files = [];
const walk = (d) => readdirSync(d).forEach((f) => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : /\.tsx?$/.test(f) && files.push(join(d, f))));
ROOTS.forEach(walk);

const re = /((?:[a-z]+:)*)(bg|text|ring|border|divide)-(up|down|foreground|background|card|muted-foreground|muted|border|black|white|primary|\[#[0-9a-fA-F]{6}\])\/(\d+|\[[\d.]+\])/g;
const found = new Map();
for (const f of files) for (const m of readFileSync(f, "utf8").matchAll(re)) found.set(m[0], m);

const esc = (s) => s.replace(/([:/[\]#.])/g, "\\$1");
const alphaOf = (a) => (a.startsWith("[") ? Number(a.slice(1, -1)) : Number(a) / 100);
const color = (name, a) => {
  if (name.startsWith("[#")) {
    const h = name.slice(2, -1);
    return `rgb(${parseInt(h.slice(0, 2), 16)} ${parseInt(h.slice(2, 4), 16)} ${parseInt(h.slice(4, 6), 16)} / ${a})`;
  }
  if (FIXED[name]) return `rgb(${FIXED[name]} / ${a})`;
  return `rgb(var(--wc-${name}) / calc(var(--wa-${name}, 1) * ${a}))`;
};

const rules = [];
for (const [cls, m] of [...found].sort(([a], [b]) => a.localeCompare(b))) {
  const [, variants, util, name, alpha] = m;
  const vs = variants.split(":").filter(Boolean);
  if (vs.some((v) => !["hover", "dark", "placeholder"].includes(v))) continue; // sm: etc. are desktop-only
  let sel = `.${esc(cls)}`;
  if (vs.includes("hover")) sel += ":hover";
  if (vs.includes("dark")) sel += ':is([data-theme="terminal"] *)';
  if (vs.includes("placeholder")) sel += "::placeholder";
  const c = color(name, alphaOf(alpha));
  const decl = { bg: `background-color: ${c}`, text: `color: ${c}`, border: `border-color: ${c}`, ring: `--tw-ring-color: ${c}`, divide: `border-color: ${c}` }[util];
  rules.push(util === "divide" ? `  ${sel} > :not(:last-child) { ${decl}; }` : `  ${sel} { ${decl}; }`);
}

const vars = Object.entries(THEMES)
  .map(([t, cs]) => `  [data-theme="${t}"] {\n${Object.entries(cs).map(([k, v]) => (Array.isArray(v) ? `    --wc-${k}: ${v[0]};\n    --wa-${k}: ${v[1]};` : `    --wc-${k}: ${v};`)).join("\n")}\n  }`)
  .join("\n");

// dvh needs Chromium 108+; older engines drop min-h-dvh entirely and the wallet stops being full-height.
const dvh = `@supports not (height: 100dvh) {\n  .min-h-dvh { min-height: 100vh; }\n}\n`;

writeFileSync(
  OUT,
  `/* Generated by scripts/wallet-compat-css.mjs — do not edit. Fallbacks for older engines (Chromium 99 system WebViews). */\n@supports not (color: color-mix(in lab, red, red)) {\n${vars}\n${rules.join("\n")}\n}\n${dvh}`,
);
console.log(`${OUT}: ${rules.length} rules from ${files.length} files`);
