/** 根据经纬度就近匹配城市 */
export function nearestCity(lat: number, lng: number): string {
  let best = '';
  let bestDist = Infinity;
  for (const [name, cLat, cLng] of CITY_COORDS) {
    const d = (cLat - lat) ** 2 + (cLng - lng) ** 2;
    if (d < bestDist) {
      bestDist = d;
      best = name;
    }
  }
  return best;
}

/** 浏览器定位并匹配最近城市；失败返回 null */
export function locateCity(): Promise<string | null> {
  return new Promise((resolve) => {
    if (!navigator.geolocation) {
      resolve(null);
      return;
    }
    navigator.geolocation.getCurrentPosition(
      (pos) => resolve(nearestCity(pos.coords.latitude, pos.coords.longitude)),
      () => resolve(null),
      { timeout: 8000, maximumAge: 600000 },
    );
  });
}
